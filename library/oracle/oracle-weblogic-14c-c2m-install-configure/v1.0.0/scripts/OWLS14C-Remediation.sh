#!/bin/sh
# OWLS14C-Remediation.sh — preview and (only with --apply) fix safe WebLogic 14c C2M config drift.
#
# PURPOSE
#     Correct the common, safe configuration drift the Validation script flags on
#     the WebLogic 14c domain for C2M: Test-On-Reserve OFF on the C2MDataSource
#     data source, the data source targeted at AdminServer instead of the managed
#     servers, and Node Manager StartScriptEnabled=false. DRY-RUN by default — it
#     prints exactly what it would change and touches nothing until you pass --apply.
#
# HOW TO RUN
#     Preview (default, no changes):
#         ./OWLS14C-Remediation.sh --domain your-domain-home/c2m_domain \
#             --admin-url t3://your-admin-host:7001 --user your-admin-user
#     Apply (after review + a verified domain backup):
#         ./OWLS14C-Remediation.sh --apply --domain your-domain-home/c2m_domain \
#             --admin-url t3://your-admin-host:7001 --user your-admin-user
#     Values also read from owls14c-scope.env if present; password from
#     OWLS14C_ADMIN_PASS. Needs ORACLE_HOME (for WLST) on PATH or exported.
#
# EXPECTED RESULTS
#     DRY-RUN: a numbered plan of the fixes it would make, then "No changes made."
#     APPLY:   each fix confirmed, the edit session activated, and a note to re-run
#              OWLS14C-Validation.py. Exit 0 on success; non-zero on error.
#
# NOTES
#     White-label, repeatable: preview in every environment, apply only after
#     review and backup. Safe by default (dry-run); it only ever adjusts the three
#     low-risk settings above — it never creates/deletes servers or changes
#     credentials. Back up the domain before --apply.

set -e

DOMAIN_HOME="your-domain-home/c2m_domain"
ADMIN_URL="t3://your-admin-host:7001"
ADMIN_USER="your-admin-user"
DS_NAME="C2MDataSource"
NM_HOME=""
APPLY="false"

# load scope file if present (does not override explicit flags below)
if [ -f "./owls14c-scope.env" ]; then
  # shellcheck disable=SC1091
  . ./owls14c-scope.env
  [ -n "$OWLS14C_DOMAIN_HOME" ] && DOMAIN_HOME="$OWLS14C_DOMAIN_HOME"
  [ -n "$OWLS14C_ADMIN_URL" ]   && ADMIN_URL="$OWLS14C_ADMIN_URL"
  [ -n "$OWLS14C_ADMIN_USER" ]  && ADMIN_USER="$OWLS14C_ADMIN_USER"
  [ -n "$OWLS14C_DS_NAME" ]     && DS_NAME="$OWLS14C_DS_NAME"
fi

while [ $# -gt 0 ]; do
  case "$1" in
    --apply)     APPLY="true" ;;
    --domain)    DOMAIN_HOME="$2"; shift ;;
    --admin-url) ADMIN_URL="$2"; shift ;;
    --user)      ADMIN_USER="$2"; shift ;;
    --ds)        DS_NAME="$2"; shift ;;
    -h|--help)   grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

echo "===================================================================="
echo " OWLS14C Remediation — WebLogic 14c for C2M"
echo "===================================================================="
echo " Domain    : $DOMAIN_HOME"
echo " Admin URL : $ADMIN_URL"
echo " Data src  : $DS_NAME"
if [ "$APPLY" = "true" ]; then
  echo " Mode      : APPLY  (changes WILL be made — ensure you have a backup)"
else
  echo " Mode      : DRY-RUN (no changes; pass --apply to make them)"
fi
echo ""

# Password: from env or prompt (not echoed)
if [ -z "$OWLS14C_ADMIN_PASS" ]; then
  printf " AdminServer password: "
  stty -echo 2>/dev/null || true
  read OWLS14C_ADMIN_PASS
  stty echo 2>/dev/null || true
  echo ""
fi
export OWLS14C_ADMIN_PASS

# Locate WLST
if [ -n "$ORACLE_HOME" ] && [ -x "$ORACLE_HOME/oracle_common/common/bin/wlst.sh" ]; then
  WLST="$ORACLE_HOME/oracle_common/common/bin/wlst.sh"
elif command -v wlst.sh >/dev/null 2>&1; then
  WLST="wlst.sh"
else
  WLST="java weblogic.WLST"
fi

WORK="$(mktemp -t owls14c-remediate.XXXXXX.py)"
trap 'rm -f "$WORK"' EXIT

cat > "$WORK" <<PYEOF
# Generated by OWLS14C-Remediation.sh — do not edit by hand.
import os
apply_changes = ('${APPLY}' == 'true')
ds   = '${DS_NAME}'
url  = '${ADMIN_URL}'
user = '${ADMIN_USER}'
pw   = os.environ.get('OWLS14C_ADMIN_PASS', '')
plan = []

connect(user, pw, url)
edit()
startEdit()
changed = 0

# 1) Test-On-Reserve on the data source
try:
    cd('/JDBCSystemResources/' + ds + '/JDBCResource/' + ds +
       '/JDBCConnectionPoolParams/' + ds)
    tor = get('TestConnectionsOnReserve')
    if not (tor == 1 or str(tor) == 'true'):
        plan.append('Enable Test-On-Reserve on ' + ds + ' (table SQL ISVALID)')
        if apply_changes:
            cmo.setTestConnectionsOnReserve(true)
            if not get('TestTableName'):
                cmo.setTestTableName('SQL ISVALID')
            changed = changed + 1
except Exception, e:
    print('  ! Could not inspect Test-On-Reserve: ' + str(e))

# 2) Data source targeted at AdminServer -> report only (retarget is topology-specific)
try:
    cd('/SystemResources/' + ds)
    tgts = get('Targets'); names = []
    if tgts is not None:
        for t in tgts:
            names.append(t.getName())
    if 'AdminServer' in names:
        plan.append('MANUAL: ' + ds + ' is targeted at AdminServer — retarget to the '
                    'managed server(s)/cluster (topology-specific; not auto-applied)')
except Exception, e:
    print('  ! Could not inspect targets: ' + str(e))

# 3) Node Manager StartScriptEnabled
try:
    for m in ls('/Machines', returnMap='true'):
        for nm in ls('/Machines/' + m + '/NodeManager', returnMap='true'):
            cd('/Machines/' + m + '/NodeManager/' + nm)
            # StartScriptEnabled lives in nodemanager.properties (file), not config MBeans.
            plan.append('CHECK: ensure StartScriptEnabled=true in '
                        + '\${DOMAIN_HOME}/nodemanager/nodemanager.properties for machine ' + m
                        + ' (file setting; edit + restart Node Manager if false)')
except Exception:
    pass

print('')
print('Remediation plan:')
if len(plan) == 0:
    print('  (nothing to change — foundation already meets these checks)')
else:
    i = 1
    for p in plan:
        print('  %d. %s' % (i, p))
        i = i + 1

if apply_changes and changed > 0:
    save()
    activate()
    print('')
    print('Applied %d change(s) and activated the edit session.' % changed)
    print('Re-run OWLS14C-Validation.py to confirm.')
else:
    try:
        stopEdit('y')
    except:
        pass
    if apply_changes:
        print('')
        print('No auto-applicable changes; manual items above (if any) remain for you.')
    else:
        print('')
        print('DRY-RUN complete. No changes made. Re-run with --apply to apply the safe fixes.')

disconnect()
PYEOF

$WLST "$WORK"
echo ""
echo "Remediation run complete."
