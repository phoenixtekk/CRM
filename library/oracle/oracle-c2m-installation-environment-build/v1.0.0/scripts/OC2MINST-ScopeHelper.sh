#!/bin/sh
# OC2MINST-ScopeHelper.sh — resolve and confirm the target C2M environment before you act.
#
# PURPOSE
#     Resolves the key coordinates of one C2M environment (your-env, e.g. C2MDEV, C2MTST, C2MPRD) so
#     every command runs against the intended tier: the environment name ($SPLENVIRON), product home
#     ($SPLEBASE), output dir ($SPLOUTPUT), WebLogic domain (c2m_domain), and the ENVIRON.INI-recorded
#     database. It prints what it resolved and, for a Production target, requires explicit confirmation
#     before it prints an "OK to proceed". Read-only: it inspects, it does not install or change.
#
# HOW TO RUN
#     Print the resolved scope for an environment (as the product OS user cissys):
#         ./OC2MINST-ScopeHelper.sh -e your-env
#     Guard a Production run (must pass -confirm C2MPRD to get an OK-to-proceed):
#         ./OC2MINST-ScopeHelper.sh -e C2MPRD -confirm C2MPRD
#
# EXPECTED RESULTS
#     A printed scope block for the environment (env name, SPLEBASE, SPLOUTPUT, domain, DB) with each
#     item marked OK or CHECK. Exit 0 and "OK to proceed" only when resolution succeeds and, for a
#     Production target, the -confirm value matches. Otherwise a non-zero exit and no go-ahead.
#
# NOTES
#     White-label, repeatable targeting guard — the way to avoid running a Dev/Test command against
#     Production. Read-only. It reads ENVIRON.INI (generated by the installer) but never edits it.
#     Directory conventions match the Installation Guide; adjust the bases below if you deviated.

ENV_NAME=""
CONFIRM=""

# -confirm is multi-char; strip it before getopts.
NEWARGS=""
SKIP="no"
for a in "$@"; do
  if [ "$SKIP" = "yes" ]; then CONFIRM="$a"; SKIP="no"; continue; fi
  if [ "$a" = "-confirm" ]; then SKIP="yes"; else NEWARGS="$NEWARGS $a"; fi
done
# shellcheck disable=SC2086
set -- $NEWARGS

while getopts "e:h" opt; do
  case "$opt" in
    e) ENV_NAME="$OPTARG" ;;
    h) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Usage: $0 -e your-env [-confirm your-env]"; exit 2 ;;
  esac
done

[ -z "$ENV_NAME" ] && { echo "ERROR: -e your-env is required."; exit 2; }

SPL_BASE_ROOT="/opt/oracle/spl"
SPL_OUT_ROOT="/opt/oracle/splout"
SPLEBASE="$SPL_BASE_ROOT/$ENV_NAME"
SPLOUTPUT="$SPL_OUT_ROOT/$ENV_NAME"
ENVIRON_INI="$SPLEBASE/etc/ENVIRON.INI"
DOMAIN="c2m_domain"

STATUS="OK"
mark() { if [ "$1" = "CHECK" ]; then STATUS="CHECK"; fi; printf "  [%-5s] %s\n" "$1" "$2"; }

echo "=== OC2MINST ScopeHelper — resolving environment: $ENV_NAME ==="
echo "  \$SPLENVIRON : $ENV_NAME"

if [ -d "$SPLEBASE" ]; then mark OK "\$SPLEBASE  : $SPLEBASE"; else mark CHECK "\$SPLEBASE not found: $SPLEBASE"; fi
if [ -d "$SPLOUTPUT" ]; then mark OK "\$SPLOUTPUT : $SPLOUTPUT"; else mark CHECK "\$SPLOUTPUT not found: $SPLOUTPUT"; fi

echo "  WebLogic domain : $DOMAIN (under \$SPLEBASE)"

if [ -f "$ENVIRON_INI" ]; then
  mark OK "ENVIRON.INI present: $ENVIRON_INI"
  # Read (never write) a couple of recorded values so you can confirm the tier is what you expect.
  DB_LINE=$(grep -iE '^DBNAME=|^DB_NAME=|^DB=' "$ENVIRON_INI" 2>/dev/null | head -n 1)
  ENVID_LINE=$(grep -iE '^SPLENVIRON=|^ENVIRONMENT=' "$ENVIRON_INI" 2>/dev/null | head -n 1)
  [ -n "$DB_LINE" ]    && echo "  ENVIRON.INI DB   : $DB_LINE"    || mark CHECK "no DB entry read from ENVIRON.INI — verify manually"
  [ -n "$ENVID_LINE" ] && echo "  ENVIRON.INI env  : $ENVID_LINE" || echo "  (env id line not matched; verify the ENVIRON.INI key name for your release)"
else
  mark CHECK "ENVIRON.INI not found ($ENVIRON_INI) — environment may not be installed"
fi

# Production guard: refuse an OK-to-proceed for a *PRD environment unless -confirm matches.
case "$ENV_NAME" in
  *PRD*)
    echo "--- Production target guard ---"
    if [ "$CONFIRM" = "$ENV_NAME" ]; then
      mark OK "Production confirmation matched (-confirm $ENV_NAME)"
    else
      mark CHECK "Production target: pass -confirm $ENV_NAME to proceed (this is a safety gate)"
    fi
    ;;
esac

echo "=== Scope resolution: $STATUS ==="
if [ "$STATUS" = "OK" ]; then
  echo "  OK to proceed against $ENV_NAME."
  exit 0
else
  echo "  Not OK to proceed — resolve the CHECK items above first."
  exit 1
fi
